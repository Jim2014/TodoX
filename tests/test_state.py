import os
import sys
import shutil

# Add project root to sys.path
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from orchestrator.storage import get_data_dir, load_task, load_projects
from orchestrator.worker import execute_ai_task
from web.app import app
from fastapi.testclient import TestClient

client = TestClient(app)

def test_full_lifecycle():
    print("--- Starting TodoX State Lifecycle Test ---")
    data_dir = get_data_dir()
    
    pid = "TESTSYS"
    
    # 1. Clear TESTSYS project for testing
    print(f"1. Cleaning up previous {pid} project...")
    client.delete(f"/api/projects/{pid}")
        
    print("2. Creating project via API...")
    response = client.post("/api/projects", json={
        "pid": pid,
        "title": "Test System Project",
        "desc": "A test project to verify state machine transitions"
    })
    assert response.status_code == 200, f"API create project failed: {response.text}"
    
    projects = load_projects()
    assert pid in projects, "Project should be in projects.json"
    assert os.path.exists(os.path.join(data_dir, "projects", pid, "files")), "Empty files directory should exist"
    
    # 2. Add a subtask via API
    print("2. Creating subtask via API...")
    response = client.post(f"/api/tasks/{pid}/{pid}-0", json={
        "title": "First generated subtask",
        "desc": "Verify AI execution mock logic",
        "assignee": "Admin"
    })
    assert response.status_code == 200, f"API create task failed: {response.text}"
    task_id = response.json().get("tid")
    assert task_id, "Response should have returned new TID"
    
    # 3. Assign to AI via API
    print("3. Assigning subtask to AI via API...")
    response = client.put(f"/api/tasks/{pid}/{task_id}", json={
        "assignee": "AI",
        "status": "in_progress"
    })
    assert response.status_code == 200, f"API update task failed: {response.text}"
    
    # 4. Trigger AI Worker (mocked out via gemini CLI)
    print("4. Triggering AI worker...")
    execute_ai_task(pid)
    
    # 5. Verify task completion
    print("5. Verifying completion state...")
    completed_task = load_task(pid, f"{pid}-0")
    assert completed_task.status in ["complete", "failed"], f"Expected complete or failed status, got {completed_task.status}"
    assert completed_task.assignee == "Admin", "Assignee should revert to Admin after completion"
    assert len(completed_task.comments) > 0, "No comment generated by AI Worker"
    
    print("\nAI Worker execution result:")
    print(completed_task.comments[-1].content)
    
    # 6. Cleanup
    print(f"6. Cleaning up {pid} project after test...")
    response = client.delete(f"/api/projects/{pid}")
    assert response.status_code == 200, f"Failed to clean up {pid}"
    
    print("\nAll tasks passed successfully!")

if __name__ == "__main__":
    test_full_lifecycle()
