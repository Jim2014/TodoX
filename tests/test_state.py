import os
import sys
import shutil

# Add project root to sys.path
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from orchestrator.storage import get_data_dir, create_project, load_task, save_task, load_projects
from orchestrator.worker import execute_ai_task

def test_full_lifecycle():
    print("--- Starting TodoX State Lifecycle Test ---")
    data_dir = get_data_dir()
    
    # 1. Clear data dir for testing
    if os.path.exists(data_dir):
        shutil.rmtree(data_dir)
        
    print("1. Creating project...")
    pid = "TESTSYS"
    create_project(
        pid=pid,
        title="Test System Project",
        descriptions="A test project to verify state machine transitions",
        system_prompt="Test Agent Prompt"
    )
    
    projects = load_projects()
    assert pid in projects, "Project should be in projects.json"
    
    # 2. Add a subtask
    print("2. Creating subtask...")
    task_id = f"{pid}-1"
    
    from orchestrator.models import Task
    subtask = Task(
        id=task_id,
        title="First generated subtask",
        descriptions="Verify AI execution mock logic",
        parent_id=f"{pid}-0"
    )
    save_task(pid, subtask)
    
    # Update parent child_ids
    parent_task = load_task(pid, f"{pid}-0")
    parent_task.child_ids.append(task_id)
    save_task(pid, parent_task)
    
    # 3. Assign to AI
    print("3. Assigning subtask to AI...")
    loaded_subtask = load_task(pid, task_id)
    loaded_subtask.assignee = "AI"
    loaded_subtask.status = "in_progress"
    save_task(pid, loaded_subtask)
    
    # 4. Trigger Worker Manually
    print("4. Triggering AI worker...")
    execute_ai_task(pid, task_id)
    
    # 5. Verify task completion
    print("5. Verifying completion state...")
    completed_task = load_task(pid, task_id)
    assert completed_task.status in ["complete", "failed"], f"Expected complete or failed status, got {completed_task.status}"
    assert completed_task.assignee == "Admin", "Assignee should revert to Admin after completion"
    assert len(completed_task.comments) > 0, "No comment generated by AI Worker"
    
    print("\nAI Worker execution result:")
    print(completed_task.comments[-1].content)
    
    print("\nAll tasks passed successfully!")

if __name__ == "__main__":
    test_full_lifecycle()
